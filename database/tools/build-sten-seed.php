<?php
/**
 * Generates database/migrations/027_table_stens.sql from docs/scoring/stens.json (written by
 * docs/scoring/derive_norms.py). Norm set v2 keeps v1's means, SDs, percentiles and domain norms, and
 * adds one sten for every attainable raw score of every factor, read from the real distribution.
 *
 * Usage:  php database/tools/build-sten-seed.php
 * The generated SQL is committed; re-run only when stens.json changes (and then as a new migration).
 */
declare(strict_types=1);

const FACTOR_ORDER = ['A', 'B', 'C', 'E', 'F', 'G', 'H', 'I', 'L', 'M', 'N', 'O', 'Q1', 'Q2', 'Q3', 'Q4'];

function fail(string $msg): never
{
    fwrite(STDERR, "ERROR: $msg\n");
    exit(1);
}

$root = dirname(__DIR__, 2);
$stens = json_decode((string) file_get_contents("$root/docs/scoring/stens.json"), true, flags: JSON_THROW_ON_ERROR);
$norms = json_decode((string) file_get_contents("$root/docs/scoring/norms.json"), true, flags: JSON_THROW_ON_ERROR);

$v2 = $stens['version'];
$v1 = $stens['base'];
if ($v1 !== $norms['version'] || $stens['n'] !== $norms['n'] || $stens['method'] !== 'table') {
    fail('stens.json does not belong to norms.json');
}
if (!preg_match('/^[a-z0-9.-]{1,30}$/', $v2)) {
    fail("bad version $v2");
}

$rows = [];
foreach (FACTOR_ORDER as $f) {
    $k = $norms['factors'][$f]['items'] ?? fail("norms.json has no factor $f");
    $table = $stens['factors'][$f] ?? fail("stens.json has no factor $f");
    $previous = 1;
    for ($raw = $k; $raw <= 5 * $k; $raw++) {
        $sten = $table[(string) $raw] ?? fail("factor $f has no sten for raw score $raw");
        if (!is_int($sten) || $sten < 1 || $sten > 10 || $sten < $previous) {
            fail("factor $f raw $raw: sten $sten is out of range or lower than the score below it");
        }
        $previous = $sten;
        $rows[] = "('$v2', '$f', $raw, $sten)";
    }
    if (count($table) !== 4 * $k + 1) {
        fail("factor $f: expected " . (4 * $k + 1) . ' raw scores, found ' . count($table));
    }
}

$cuts = implode(', ', $stens['cuts']);
$sql = <<<SQL
-- GENERATED by database/tools/build-sten-seed.php from docs/scoring/stens.json. Do not edit by hand.
--
-- Norm set $v2 (owner decision 2026-10-16, "option A"): the same $stens[n] people as $v1, but each factor's
-- sten is read from the real score distribution (mid-rank share of people, standard sten cut-points
-- $cuts %) instead of 2z + 5.5, so the sten, the percentile and the band always agree.
-- Global domains still use 2z + 5.5. Sessions already scored keep $v1 and their stored scores.

ALTER TABLE norm_sets
  ADD COLUMN sten_method ENUM('formula', 'table') NOT NULL DEFAULT 'formula' AFTER sample_size;

CREATE TABLE factor_stens (
  norm_version VARCHAR(30)       NOT NULL,
  factor_code  VARCHAR(3)        NOT NULL,
  raw_score    SMALLINT UNSIGNED NOT NULL,
  sten         TINYINT UNSIGNED  NOT NULL,
  PRIMARY KEY (norm_version, factor_code, raw_score),
  CONSTRAINT fk_factor_stens_set FOREIGN KEY (norm_version) REFERENCES norm_sets (version),
  CONSTRAINT fk_factor_stens_factor FOREIGN KEY (factor_code) REFERENCES factors (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO norm_sets (version, source, sample_size, sten_method, is_active)
SELECT '$v2', CONCAT(source, '; stens from the real distribution'), sample_size, 'table', 0 FROM norm_sets WHERE version = '$v1';

INSERT INTO factor_norms (norm_version, factor_code, mean, sd, n, alpha)
SELECT '$v2', factor_code, mean, sd, n, alpha FROM factor_norms WHERE norm_version = '$v1';

INSERT INTO factor_percentiles (norm_version, factor_code, raw_score, percentile)
SELECT '$v2', factor_code, raw_score, percentile FROM factor_percentiles WHERE norm_version = '$v1';

INSERT INTO domain_norms (norm_version, domain_code, mean, sd)
SELECT '$v2', domain_code, mean, sd FROM domain_norms WHERE norm_version = '$v1';

INSERT INTO factor_stens (norm_version, factor_code, raw_score, sten) VALUES

SQL;
$sql .= implode(",\n", $rows) . ";\n\n";
$sql .= "-- New tests are scored with $v2; finished tests keep the version they were scored with.\n";
$sql .= "UPDATE norm_sets SET is_active = IF(version = '$v2', 1, 0);\n";

file_put_contents("$root/database/migrations/027_table_stens.sql", $sql);
echo 'wrote database/migrations/027_table_stens.sql (' . count($rows) . " sten rows)\n";
